def con_ids(zona):
    """[(id, tipo, mapa)] con ids correlativos por tipo: bosque_combate_01, bosque_combate_02..."""
    cuenta, salida = {}, []
    for tipo, mapa in PLANTILLAS[zona]:
        assert len(mapa) == 11 and all(len(fila) == 15 for fila in mapa), (zona, tipo)
        cuenta[tipo] = cuenta.get(tipo, 0) + 1
        salida.append((f"{zona}_{tipo}_{cuenta[tipo]:02d}", tipo, mapa))
    return salida
